"""Validate NEBULA project skills and subagents; writes .claude/skills/SKILL_VALIDATION_REPORT.md.

Checks: YAML frontmatter parses; `name` matches directory and is kebab-case <= 64 chars; description
present (<= 1024 chars) and says when to use; required sections present; referenced files exist;
SKILL.md body is focused (<= 500 lines). Agents: frontmatter with name/description/tools.
Usage: uv run python scripts/validate_skills.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SKILLS = ROOT / ".claude" / "skills"
AGENTS = ROOT / ".claude" / "agents"
REQUIRED = ["Purpose", "Activate when", "Failure modes", "Verification", "Limitations", "Interacts with"]
EXPECTED = [
    "quantitative-research",
    "financial-data-engineering",
    "backtesting-audit",
    "market-microstructure",
    "financial-ml-research",
    "portfolio-risk-engineering",
    "research-paper-analysis",
]


def frontmatter(text: str) -> tuple[dict, str]:
    m = re.match(r"^---\r?\n(.*?)\r?\n---\r?\n(.*)$", text, re.S)
    if not m:
        raise ValueError("missing frontmatter")
    return yaml.safe_load(m.group(1)), m.group(2)


def check_skill(d: Path) -> list[str]:
    problems = []
    f = d / "SKILL.md"
    if not f.exists():
        return ["SKILL.md missing"]
    try:
        fm, body = frontmatter(f.read_text(encoding="utf-8"))
    except Exception as exc:
        return [f"frontmatter: {exc}"]
    name, desc = fm.get("name", ""), fm.get("description", "")
    if name != d.name:
        problems.append(f"name {name!r} != directory {d.name!r}")
    if not re.fullmatch(r"[a-z0-9-]{1,64}", name or ""):
        problems.append("name not kebab-case <= 64 chars")
    if not desc or len(desc) > 1024:
        problems.append("description missing or > 1024 chars")
    elif "use when" not in desc.lower():
        problems.append("description does not state when to use")
    for sec in REQUIRED:
        if not re.search(rf"^#+\s.*{re.escape(sec)}", body, re.M | re.I):
            problems.append(f"section missing: {sec}")
    for ref in re.findall(r"`(references/[^`]+)`", body):
        if not (d / ref).exists():
            problems.append(f"broken reference {ref}")
    if body.count("\n") > 500:
        problems.append("SKILL.md body > 500 lines")
    return problems


def check_agent(f: Path) -> list[str]:
    try:
        fm, body = frontmatter(f.read_text(encoding="utf-8"))
    except Exception as exc:
        return [f"frontmatter: {exc}"]
    problems = [f"missing {k}" for k in ("name", "description", "tools") if not fm.get(k)]
    if fm.get("name") != f.stem:
        problems.append("name != filename")
    if not body.strip():
        problems.append("empty system prompt")
    return problems


def main() -> int:
    rows, failed = [], False
    present = sorted(p.name for p in SKILLS.iterdir() if p.is_dir())
    for name in EXPECTED:
        probs = check_skill(SKILLS / name) if name in present else ["directory missing"]
        failed |= bool(probs)
        rows.append(("skill", name, "PASS" if not probs else "FAIL", "; ".join(probs)))
    for f in sorted(AGENTS.glob("*.md")):
        probs = check_agent(f)
        failed |= bool(probs)
        rows.append(("agent", f.stem, "PASS" if not probs else "FAIL", "; ".join(probs)))
    lines = [
        "# Skill validation report",
        "",
        "Generated by `scripts/validate_skills.py` (rewritten only when results change).",
        "",
        "| Kind | Name | Result | Problems |",
        "|---|---|---|---|",
        *[f"| {k} | {n} | {r} | {p or '-'} |" for k, n, r, p in rows],
        "",
        "Static checks only. Discoverability inside Claude Code requires opening a session in the",
        "project folder (project skills/agents load at session start) - see PROJECT_STATUS.",
    ]
    content = "\n".join(lines) + "\n"
    out = SKILLS / "SKILL_VALIDATION_REPORT.md"
    if not out.exists() or out.read_text(encoding="utf-8") != content:
        with out.open("w", encoding="utf-8", newline="\n") as fh:  # LF, matches .gitattributes
            fh.write(content)
    print(content, end="")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
